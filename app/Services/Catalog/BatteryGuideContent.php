<h3 id="tech-ca">Ca: кальциевые аккумуляторы</h3>
<p>В пластинах добавлен кальций. Такие аккумуляторы мало расходуют воду и медленно саморазряжаются, поэтому обычно не требуют обслуживания. Это самый распространённый вариант для автомобилей без Start-Stop.</p>

<h3 id="tech-ca-ag">Ca+Ag: кальций с серебром</h3>
<p>К кальциевым пластинам добавлено серебро. Оно повышает стойкость решёток к коррозии и улучшает приём заряда, поэтому такой аккумулятор обычно служит дольше обычного кальциевого. Подходит тем же автомобилям, что и Ca, если хочется запас по сроку службы.</p>

<h3 id="tech-gel">Gel: гелевые аккумуляторы</h3>
<p>Электролит загущен до состояния геля. Такие аккумуляторы хорошо переносят глубокие разряды и наклон корпуса, поэтому их ставят на лодки, электротранспорт и в источники резервного питания. Для обычного запуска двигателя их берут редко: они хуже отдают большой пусковой ток и требуют подходящего режима зарядки. От AGM гель отличается тем, что электролит не впитан в стекловолокно, а загущен.</p>

<h3 id="tech-pb">Pb: классические свинцово-кислотные</h3>
<p>Обычные обслуживаемые аккумуляторы без кальция. В продаже они сейчас встречаются редко, поэтому в нашем каталоге их практически нет. Если вам предлагают такой вариант, уточните у менеджера, подойдёт ли он вашему автомобилю.</p>
<p>Все варианты можно посмотреть в разделе [[category:1|аккумуляторы для легковых автомобилей]].</p>

<h2 id="efb-agm">EFB или AGM: в чём разница</h2>
<p>Оба типа рассчитаны на частые пуски двигателя и работу с системой Start-Stop, но устроены по-разному. В EFB пластины усилены, а электролит остаётся жидким. В AGM электролит впитан в стекловолоконные пластины, корпус герметичный, поэтому такой аккумулятор лучше переносит глубокие разряды и вибрацию.</p>
<ul>
<li><strong>EFB</strong> дешевле и подходит автомобилям с базовым Start-Stop, где нагрузка на аккумулятор умеренная.</li>
<li><strong>AGM</strong> нужен, если автомобиль работает с рекуперацией энергии или у него много электроники. Он стоит дороже, зато служит дольше в тяжёлом режиме.</li>
<li>Менять AGM на EFB не стоит: он может не выдержать нагрузку. Обратная замена, EFB на AGM, допустима.</li>
</ul>

