<h2 id="capacity">Ёмкость аккумулятора: сколько ампер-часов нужно</h2>
<p>Ёмкость измеряется в ампер-часах (Ah) и показывает запас энергии: чем она больше, тем дольше аккумулятор тянет нагрузку при выключенном двигателе. Не берите ёмкость меньше рекомендованной производителем автомобиля. Немного большая допустима, если аккумулятор помещается на штатную площадку: он дольше заряжается, но работает без проблем.</p>

<h2 id="cranking-current">Пусковой ток аккумулятора: на что смотреть</h2>
<p>Пусковой ток (ток холодной прокрутки) — ток, который аккумулятор отдаёт при запуске двигателя на морозе. Чем он выше, тем увереннее зимний пуск, что особенно важно в нашем климате. Не берите ток меньше рекомендованного для вашего автомобиля.</p>
<div class="guide-tip">
<strong class="guide-tip__title">Совет специалиста</strong>
<p>Сравнивайте пусковой ток только в одном стандарте измерения, чаще всего EN. У одного и того же аккумулятора цифры в EN, SAE, DIN и ГОСТ разные: по SAE они обычно выше.</p>
</div>

<h2 id="dimensions">Габариты аккумулятора: как подобрать по размеру</h2>
<p>Длина, ширина и высота указаны в миллиметрах. Аккумулятор должен встать на штатную площадку, закрепиться планкой и не упираться в крышку отсека. Если сомневаетесь, сверьте размеры со старым аккумулятором или воспользуйтесь [[cars|подбором по марке и модели]]: там размеры уже учтены.</p>

<h2 id="case-type">Тип корпуса: что значат L2, B24, D26</h2>
<p>Тип корпуса — стандартное обозначение размера и формы аккумулятора. Европейские типы обозначают буквой L (L1, L2, L3, LB2 и другие), азиатские — буквами B и D (B19, B24, D23, D26, D31). У каждого типа свои длина, ширина и высота, например L2 — это 242 × 175 × 190 мм. Грузовые аккумуляторы у нас делятся на группы Груз A, B и C по ёмкости.</p>
<p>Тип корпуса указан в карточке товара и в фильтре каталога: выбрав тип, как у вашего старого аккумулятора, вы получите только те модели, которые встанут на штатное место. От типа корпуса зависит и скидка при сдаче старого аккумулятора, подробности на странице [[page:trade-in|трейд-ин]].</p>

